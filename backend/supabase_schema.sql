-- ============================================================================
-- AGROALERTA — ESQUEMA COMPLETO DO BANCO DE DADOS SUPABASE (POSTGRESQL)
-- ============================================================================
-- Este script cria todas as tabelas e índices necessários no Supabase.
-- Para executar: Cole este conteúdo no SQL Editor do Dashboard do Supabase e clique em RUN.
-- ============================================================================

-- Habilita extensões úteis
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";

-- ----------------------------------------------------------------------------
-- 1. TABELA DE PRODUTORES (Usuários do Telegram)
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS produtores (
    chat_id VARCHAR(64) PRIMARY KEY,
    nome_produtor VARCHAR(128),
    cultura_ativa VARCHAR(64) DEFAULT 'citros',
    tipo_solo_ativo VARCHAR(64) DEFAULT 'latossolo_vermelho',
    is_organico_ativo BOOLEAN DEFAULT TRUE,
    area_ha_ativa DOUBLE PRECISION DEFAULT 1.0,
    localizacao_padrao_lat DOUBLE PRECISION DEFAULT -22.4114,
    localizacao_padrao_lon DOUBLE PRECISION DEFAULT -47.5614,
    notificacoes_ativas BOOLEAN DEFAULT TRUE,
    criado_em TIMESTAMPTZ DEFAULT NOW(),
    atualizado_em TIMESTAMPTZ DEFAULT NOW()
);

-- ----------------------------------------------------------------------------
-- 2. TABELA DE TALHÕES GEORREFERENCIADOS (Polígonos 3 ou 4 vértices)
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS talhoes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    chat_id VARCHAR(64) NOT NULL REFERENCES produtores(chat_id) ON DELETE CASCADE,
    nome_talhao VARCHAR(128) NOT NULL,
    poligono_tipo VARCHAR(32) NOT NULL, -- 'triangulo' ou 'quadrilatero'
    vertices JSONB NOT NULL,            -- Array de coordenadas [{"lat": ..., "lon": ...}]
    centroide JSONB,                    -- Centroide da gleba {"lat": ..., "lon": ...}
    cultura VARCHAR(64) NOT NULL,       -- citros, tomate, milho, cana, alface, cafe, soja
    is_organico BOOLEAN NOT NULL DEFAULT TRUE,
    tipo_solo VARCHAR(64) NOT NULL DEFAULT 'latossolo_vermelho',
    area_ha DOUBLE PRECISION DEFAULT 1.0, -- Calculado via Shoelace Gauss
    criado_em TIMESTAMPTZ DEFAULT NOW()
);

-- ----------------------------------------------------------------------------
-- 3. TABELA DE LEITURAS DE SOLO FÍSICAS (8 Sensores Exatos)
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS leituras_solo (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    chat_id VARCHAR(64) NOT NULL REFERENCES produtores(chat_id) ON DELETE CASCADE,
    talhao_id BIGINT REFERENCES talhoes(id) ON DELETE SET NULL,
    talhao_nome VARCHAR(128),
    origem VARCHAR(32) DEFAULT 'telegram', -- 'telegram', 'app_mobile', 'esp32_iot'
    latitude DOUBLE PRECISION NOT NULL,
    longitude DOUBLE PRECISION NOT NULL,
    -- 8 Entradas Físicas Exatas do Sensor:
    ph DOUBLE PRECISION NOT NULL,          -- pH do solo
    umidade DOUBLE PRECISION NOT NULL,     -- Teor de umidade (%)
    nitrogenio DOUBLE PRECISION NOT NULL,  -- Nitrogênio N (ppm)
    fosforo DOUBLE PRECISION NOT NULL,     -- Fósforo P (ppm)
    potassio DOUBLE PRECISION NOT NULL,    -- Potássio K (ppm)
    condutividade DOUBLE PRECISION NOT NULL, -- Condutividade elétrica CE (dS/m)
    temperatura DOUBLE PRECISION NOT NULL, -- Temperatura do solo (°C)
    compactacao DOUBLE PRECISION NOT NULL, -- Compactação / Resistência mecânica (kPa)
    criado_em TIMESTAMPTZ DEFAULT NOW()
);

-- ----------------------------------------------------------------------------
-- 4. TABELA DE ANÁLISES DA IA (Rede Neural Multitarefa & Síntese da LLM)
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS analises_ia (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    leitura_id BIGINT REFERENCES leituras_solo(id) ON DELETE CASCADE,
    chat_id VARCHAR(64) NOT NULL REFERENCES produtores(chat_id) ON DELETE CASCADE,
    talhao_id BIGINT REFERENCES talhoes(id) ON DELETE SET NULL,
    talhao_nome VARCHAR(128),
    cultura VARCHAR(64) NOT NULL,
    is_organico BOOLEAN NOT NULL,
    tipo_solo VARCHAR(64) NOT NULL,
    area_ha DOUBLE PRECISION NOT NULL,
    -- Decisão de Irrigação (Rede Neural)
    classe_irrigacao INTEGER NOT NULL,     -- 0: Não irrigar, 1: Leve/Moderada, 2: Abundante
    status_irrigacao VARCHAR(128) NOT NULL,
    lamina_recomendada_mm DOUBLE PRECISION DEFAULT 0.0,
    volume_necessario_litros DOUBLE PRECISION DEFAULT 0.0, -- mm * 10.000 * area_ha
    volume_economizado_litros DOUBLE PRECISION DEFAULT 0.0, -- Litros economizados se bomba desligada
    tempo_gotejamento_minutos INTEGER DEFAULT 0,
    tempo_aspersao_minutos INTEGER DEFAULT 0,
    litros_por_planta DOUBLE PRECISION DEFAULT 0.0,
    janela_irrigacao_ideal VARCHAR(128),
    janela_pulverizacao_ideal VARCHAR(128),
    -- Trava e Clima
    trava_chuva_acionada BOOLEAN DEFAULT FALSE,
    chuva_prevista_mm DOUBLE PRECISION DEFAULT 0.0,
    probabilidade_chuva_pct DOUBLE PRECISION DEFAULT 0.0,
    -- Riscos Fitossanitários e Pragas
    alertas_pragas JSONB,                 -- Lista de riscos gerais (fungos, insetos, ácaros, estresse)
    pragas_especificas JSONB,             -- Pragas reais da cultura (Psilídeo, Requeima, etc.)
    prescricao_insumos JSONB,             -- Receitas de bioinsumos (MAPA) ou defensivos
    -- Síntese Prescritiva Gerada pelo LLM
    texto_prescritivo_llm TEXT,           -- Texto humanizado e acolhedor enviado no Telegram
    relatorio_json JSONB,                 -- Dados analíticos completos em JSON
    notificado_telegram BOOLEAN DEFAULT FALSE,
    criado_em TIMESTAMPTZ DEFAULT NOW()
);

-- ----------------------------------------------------------------------------
-- 5. TABELA DE MENSAGENS E MEMÓRIA DO TELEGRAM (Entrada & Saída da IA)
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS mensagens_telegram (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    chat_id VARCHAR(64) NOT NULL REFERENCES produtores(chat_id) ON DELETE CASCADE,
    direcao VARCHAR(16) NOT NULL,         -- 'entrada' (produtor) ou 'saida' (bot/IA)
    tipo_mensagem VARCHAR(32) DEFAULT 'texto_livre', -- 'texto_livre', 'comando', 'localizacao', 'prescricao'
    mensagem_texto TEXT NOT NULL,
    talhao_mencionado_id BIGINT REFERENCES talhoes(id) ON DELETE SET NULL,
    analise_ia_id BIGINT REFERENCES analises_ia(id) ON DELETE SET NULL,
    criado_em TIMESTAMPTZ DEFAULT NOW()
);

-- ----------------------------------------------------------------------------
-- ÍNDICES DE ALTO DESEMPENHO
-- ----------------------------------------------------------------------------
CREATE INDEX IF NOT EXISTS idx_talhoes_chat ON talhoes(chat_id);
CREATE INDEX IF NOT EXISTS idx_leituras_chat_data ON leituras_solo(chat_id, criado_em DESC);
CREATE INDEX IF NOT EXISTS idx_analises_chat_data ON analises_ia(chat_id, criado_em DESC);
CREATE INDEX IF NOT EXISTS idx_analises_talhao ON analises_ia(talhao_id);
CREATE INDEX IF NOT EXISTS idx_mensagens_chat_data ON mensagens_telegram(chat_id, criado_em DESC);
